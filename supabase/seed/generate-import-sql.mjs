#!/usr/bin/env node
/**
 * Convert semicolon-delimited Supabase CSV exports into a single SQL seed file.
 *
 * Usage:
 *   node supabase/seed/generate-import-sql.mjs \
 *     --members path/to/members.csv \
 *     --daily-records path/to/daily_records.csv \
 *     [--month-progress path/to/member_month_progress.csv] \
 *     [--out supabase/seed/import-from-export.sql]
 */

import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

const MEMBER_COLS = [
  "id",
  "name",
  "avatar_url",
  "pin_hash",
  "created_at",
  "gender",
  "active_count",
  "highest_unlocked",
  "status_id",
  "status_month",
];

const DAILY_COLS = [
  "id",
  "member_id",
  "date",
  "pushups",
  "situps",
  "squats",
  "created_at",
  "updated_at",
  "lunges",
  "glute_bridges",
  "leg_raises",
  "burpees",
];

const MONTH_PROGRESS_COLS = [
  "id",
  "member_id",
  "month",
  "status_id",
  "active_count",
  "full_days",
  "unlocked_count",
  "created_at",
  "updated_at",
];

const NULLABLE = new Set(["avatar_url", "status_month"]);

function parseArgs(argv) {
  const args = {
    members: null,
    dailyRecords: null,
    monthProgress: null,
    out: resolve("supabase/seed/import-from-export.sql"),
  };
  for (let i = 2; i < argv.length; i++) {
    const flag = argv[i];
    const value = argv[i + 1];
    if (flag === "--members" && value) {
      args.members = resolve(value);
      i++;
    } else if (flag === "--daily-records" && value) {
      args.dailyRecords = resolve(value);
      i++;
    } else if (flag === "--month-progress" && value) {
      args.monthProgress = resolve(value);
      i++;
    } else if (flag === "--out" && value) {
      args.out = resolve(value);
      i++;
    } else if (flag === "--help" || flag === "-h") {
      console.log(`Usage: node supabase/seed/generate-import-sql.mjs \\
  --members <members.csv> \\
  --daily-records <daily_records.csv> \\
  [--month-progress <member_month_progress.csv>] \\
  [--out <output.sql>]`);
      process.exit(0);
    }
  }
  if (!args.members || !args.dailyRecords) {
    console.error("Error: --members and --daily-records are required.");
    process.exit(1);
  }
  return args;
}

/** Minimal CSV parser for semicolon-separated exports (no embedded newlines in fields). */
function parseSemicolonCsv(text) {
  const lines = text.replace(/\r\n/g, "\n").replace(/\r/g, "\n").trim().split("\n");
  if (lines.length === 0) return [];
  const headers = lines[0].split(";").map((h) => h.trim());
  const rows = [];
  for (let i = 1; i < lines.length; i++) {
    const line = lines[i];
    if (!line.trim()) continue;
    const values = line.split(";");
    const row = {};
    for (let j = 0; j < headers.length; j++) {
      row[headers[j]] = values[j] ?? "";
    }
    rows.push(row);
  }
  return rows;
}

function sqlEscapeString(value) {
  return value.replace(/'/g, "''");
}

function sqlLiteral(column, raw) {
  const trimmed = raw.trim();
  if (NULLABLE.has(column) && trimmed === "") {
    return "NULL";
  }
  if (/^-?\d+$/.test(trimmed) && column !== "month" && column !== "status_id" && column !== "pin_hash") {
    return trimmed;
  }
  return `'${sqlEscapeString(trimmed)}'`;
}

function buildInsert(table, columns, rows) {
  if (rows.length === 0) return "";
  const valueLines = rows.map((row) => {
    const vals = columns.map((col) => sqlLiteral(col, row[col] ?? ""));
    return `  (${vals.join(", ")})`;
  });
  return [
    `INSERT INTO public.${table} (${columns.join(", ")})`,
    "VALUES",
    valueLines.join(",\n"),
    "ON CONFLICT DO NOTHING;",
  ].join("\n");
}

function loadCsv(path) {
  return parseSemicolonCsv(readFileSync(path, "utf8"));
}

function main() {
  const args = parseArgs(process.argv);
  const members = loadCsv(args.members);
  const dailyRecords = loadCsv(args.dailyRecords);
  const monthProgress = args.monthProgress ? loadCsv(args.monthProgress) : [];

  for (const col of MEMBER_COLS) {
    if (members.length && !(col in members[0])) {
      console.error(`members CSV missing column: ${col}`);
      process.exit(1);
    }
  }
  for (const col of DAILY_COLS) {
    if (dailyRecords.length && !(col in dailyRecords[0])) {
      console.error(`daily_records CSV missing column: ${col}`);
      process.exit(1);
    }
  }

  const parts = [
    "-- Generated by supabase/seed/generate-import-sql.mjs",
    "-- Contains pin_hash values — do not commit to public repos.",
    "BEGIN;",
    "",
    "-- members (preserve id for FKs and sessions)",
    buildInsert("members", MEMBER_COLS, members),
    "",
    "-- daily_records",
    buildInsert("daily_records", DAILY_COLS, dailyRecords),
  ];

  if (monthProgress.length > 0) {
    parts.push("", "-- member_month_progress", buildInsert("member_month_progress", MONTH_PROGRESS_COLS, monthProgress));
  }

  parts.push("", "COMMIT;", "");

  writeFileSync(args.out, parts.filter((p) => p !== "").join("\n") + "\n", "utf8");
  console.log(`Wrote ${args.out}`);
  console.log(`  members: ${members.length}`);
  console.log(`  daily_records: ${dailyRecords.length}`);
  console.log(`  member_month_progress: ${monthProgress.length}`);
}

main();
